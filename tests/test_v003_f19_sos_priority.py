#!/usr/bin/env python3
"""F19R1: emergency override, no UI-controlled SOS actions, legacy DEV intact."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
src=(ROOT/'firmware/universal/src/main.cpp').read_text(encoding='utf-8')
button=src.split('void handleOLEDButton() {',1)[1].split('\n// ============================================================\n// OLED PAGES',1)[0]
dispatch=src.split('void updateOLED() {',1)[1].split('\nvoid oledGPSPage()',1)[0]
render=src.split('// 128x64 landscape, six rows of 6x10 font.',1)[1].split('\n#endif // F19 renderer',1)[0]
sos=render.split('void oledF19SOSPage() {',1)[1]
assert button.index('if (f19ActiveSOS)')<button.index('f19Display.wake()')
assert 'f21r42SOSBrowse.observe(V003F19Display::emergencyActive(' in button
assert 'if(sosMenuOpen)' in button and 'confirmSOSMenu();' in button
assert 'f21r42SOSBrowse.tap(millis())' in button
assert 'f21r42SOSBrowse.returnToSOS(millis())' in button
assert button.index('if (f19ActiveSOS)')<button.index('f19Display.openHomeMenu')
assert dispatch.index('if (f19SOS && f21r42SOSBrowse.forceSOS())') < dispatch.index('if (f19Display.operational() || f19SOS) {')
assert 'if (f19WantOff) return' in dispatch
assert 'u8g2.setPowerSave(f19WantOff?1:0)' in dispatch
# F21R3 changed OP page dispatch, NOT hardware-authoritative SOS priority.
# Accept legacy F19 or the F21R3 two-orientation renderer, but never skip
# emergency override, output isolation, or DEV behavior checks below.
if '// F21R3: OLED-only icon/phone-style OP presentation.' in src:
 assert 'case 3: oledF21LandscapeSOSPage(); break;' in dispatch
 assert 'case 3: oledF21PortraitSOSPage(); break;' in dispatch
 assert 'case 3: oledF19SOSPage(); break;' not in dispatch
 assert 'const bool f21WantPortrait=(f19Display.operational() || f19SOS) && f19Display.portrait();' in dispatch
 assert 'u8g2.setDisplayRotation(f21WantPortrait?U8G2_R1:U8G2_R0)' in dispatch
 assert 'if (f19SOS && f21r42SOSBrowse.forceSOS()) {\n    if(f21WantPortrait)oledF21PortraitSOSPage();\n    else oledF21LandscapeSOSPage();\n    return;\n  }' in dispatch
 assert dispatch.index('if (f19WantOff) return') < dispatch.index('if (f19SOS && f21r42SOSBrowse.forceSOS())') < dispatch.index('if (f19Display.operational() || f19SOS)')
 modern=src.split('// F21R3: OLED-only icon/phone-style OP presentation.',1)[1].split('#endif // F21R3 icon renderers',1)[0]
 for function in ('void oledF21PortraitSOSPage()', 'void oledF21LandscapeSOSPage()'):
  assert function in modern, function
 for forbidden in ('transmitSOS(', 'cancelActiveSOS(', 'transmitPacket(',
                   'ThesisSDLogger::queue', 'ThesisSDLogger::hybridSetContinuous(',
                   'digitalWrite(', 'pinMode(', 'sendPacket(', 'processWeather('):
  assert forbidden not in modern, forbidden
 assert 'hasActiveLocalSOS()' in modern and 'getActiveSOSCount()' in modern
 assert 'gpsHasFix && chosen.positionValid' in modern
else:
 assert 'case 3: oledF19SOSPage(); break;' in dispatch
assert 'LOCAL: INACTIVE' in sos and 'NO ACTIVE DISTRESS' in sos
assert 'DIR: UNKNOWN' in sos and 'cardinal8(bearing)' in sos
assert '(LAST)' in sos and 'TRUE' in sos
assert 'hasActiveLocalSOS()' in sos and 'getActiveSOSCount()' in sos
for name in ('transmitSOS(', 'cancelActiveSOS(', 'transmitPacket(',
             'ThesisSDLogger::queue', 'ThesisSDLogger::hybridSetContinuous(',
             'digitalWrite(', 'pinMode('):
 assert name not in render,name
assert 'oledPage = (oledPage + 1) % kOLEDPageCount;' in button
assert 'ThesisSDLogger::hybridSetContinuous(sdHybridMenuCursor == 1)' in button
assert 'void oledMicroWeatherPage()' in src
assert 'SOSControls::pollAction(hasActiveLocalSOS())' in src
# Compile-time F19 controls are the authoritative GPIO/relay safety gate.
# The literal 'GPIO_OUTPUTS=DISABLED' is generated by another module's
# serial logging; it is not required to exist in main.cpp.
guard=src.split('// F19: new Vessel-003 presentation only;',1)[1].split(
    '// Separate F15 hardware opt-in:',1)[0]
assert 'THESIS_V003_F13_LIVE_OUTPUTS != 0' in guard
assert 'THESIS_LAB_RELAY_TX != 0' in guard
print('PASS F19: SOS initially overrides, GPIO0 browsing display-only, no SOS actions')
print('PASS F19R1: eight legacy DEV pages + hybrid SD menu retained')
