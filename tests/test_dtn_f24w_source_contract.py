#!/usr/bin/env python3
"""F24W scope checks, not a proof of global physical interposition."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
base=root/'firmware/shared/storage'
h=(base/'dtn_f24w_mount_owner.h').read_text()
l=(base/'thesis_sd_logger.h').read_text()
ini=(root/'firmware/universal/platformio.ini').read_text()
main=(root/'firmware/universal/src/main.cpp').read_text()
checks=[]
def test(label,ok):
    if not ok: raise AssertionError('F24W SOURCE FAIL: '+label)
    checks.append(label)
test('owner final','class MountOwner final' in h)
test('owner noncopyable','MountOwner(const MountOwner&)=delete' in h)
test('owner nonmovable','MountOwner(MountOwner&&)=delete' in h)
test('token final','class Token final' in h)
test('token copy deleted','Token(const Token&)=delete' in h)
test('token move assignment deleted','Token& operator=(Token&&)=delete' in h)
test('token move invalidates source','o.owner_=nullptr;' in h)
test('no destructor in token','~Token' not in h)
test('backend destructor constraint','std::is_trivially_destructible<Backend>::value' in h)
test('slot owns state','Slot slots_[2]{}' in h)
test('token has stamp','uint64_t stamp_=0;' in h)
test('slot matching owner and generation','t.owner_==this' in h and 'slots_[t.slot_].stamp==t.stamp_' in h)
test('backend stored privately','const Witness& w_; Backend backend_' in h)
test('owner checks exclusive witness','i.authorized && i.exclusive && i.allPathsInterposed' in h)
test('epoch monotonic','i.epoch<=lastEpoch_' in h)
test('post mount witness','!backend_.mount() || !same()' in h)
test('reserve before open','!reserve(0,mode) || !backend_.open(0,path,mode) || !same()' in h)
test('child reserve before call',h.index('!reserve(1,Mode::Read)')<h.index('backend_.child(0,1)'))
test('child post witness','if(!ok || !same())' in h)
test('io post witness','!backend_.io(t.slot_,a,data,n) || !same()' in h)
test('parent cannot close first','if(t.slot_==0 && slots_[1].used)return false;' in h)
test('quiesce before drain',h.index('state_=State::Draining;')<h.index('slots_[1].used && !closeSlot(1)'))
test('child before parent before unmount',h.index('slots_[1].used && !closeSlot(1)')<h.index('slots_[0].used && !closeSlot(0)')<h.index('!backend_.unmount()'))
test('flush before close before slot release',h.index('!backend_.flush(s)')<h.index('!backend_.close(s)')<h.index('slots_[s]={};'))
test('close failure quarantines','!backend_.close(s) || !same())return fail()' in h)
test('unmount failure quarantines','!backend_.unmount() || !same())return fail()' in h)
test('fault sticky','bool fail(){state_=State::Faulted;return false;}' in h and 'state_!=State::Detached)return false' in h)
test('reentry barrier','if(ok)busy=true;' in h and h.count('Call c(busy_)')==6)
test('never backend','struct NeverBackend' in h)
test('permanent witness','struct DenyWitness { Identity view()const{return {};} }' in h)
test('facade private owner','MountOwner<NeverBackend,DenyWitness> owner_{witness_};' in h)
test('facade denied begin','(void)owner_.mount();return false;' in h)
test('facade empty file','FileType open(A&&...){return FileType{};}' in h)
test('facade denied end','bool end(){return owner_.shutdown();}' in h)
test('no actual SD header','<SD.h>' not in h and 'SD.' not in h)
test('no actual POSIX calls',all(x not in h for x in ['fopen(', 'fclose(', 'fsync(', 'closedir(']))
test('no transport code','RadioLib' not in h and 'WiFi' not in h)
test('F24W flag defaults off','#define THESIS_DTN_F24W_BUILD_ONLY 0' in l)
test('flag validation','THESIS_DTN_F24W_BUILD_ONLY != 0 && THESIS_DTN_F24W_BUILD_ONLY != 1' in l)
block=l[l.index('// F24W: owner-held slot lifecycle preview.'):l.index('namespace ThesisSDLogger {')]
for f in ['THESIS_DTN_F24V_BUILD_ONLY','THESIS_DTN_F24K_SD_INTERPOSE_BUILD_ONLY']:
    test('requires '+f,f+' != 1' in block)
for f in ['THESIS_F23D_SD_EVIDENCE','THESIS_F22_FLEET_OPERATIONAL','THESIS_LAB_RELAY_TX','THESIS_V003_F13_LIVE_OUTPUTS','THESIS_SD_PROBE']:
    test('denies '+f,f+' != 0' in block)
test('F24W actual facade selection','#if THESIS_DTN_F24W_BUILD_ONLY == 1\nstatic DTNF24W::DenyMountFacade<File> interposedSD;' in l)
test('previous facade preserved','#else\nstatic DTNF24K::DenySdFacade<File> interposedSD;\n#endif' in l)
test('legacy outside F24K','static auto& interposedSD = SD;' in l)
test('actual begin call','interposedSD.begin(47, sdSPI, 1000000, "/sd", 5, false)' in l)
test('actual F24O and R remain denied','f24oNoPhysicalWitness' in l and 'f24rNoPhysicalWitness' in l and 'f24rNoLease{}' in l)
test('probe conditional','#if THESIS_SD_PROBE == 1\n#include "../../shared/storage/sd_probe.h"' in main)
profile=ini.split('[env:tbeam-supreme-f24w-mount-owner-deny-build-only]')[1]
test('F24W extends F24V','extends = env:tbeam-supreme-f24v-core-close-deny-build-only' in profile)
test('F24W flag enabled','-D THESIS_DTN_F24W_BUILD_ONLY=1' in profile)
test('no profile upload setting','upload_protocol' not in profile)
print(f'F24W owner lifecycle deny-profile source contract PASS: {len(checks)} checks; not physical interposition proof')
